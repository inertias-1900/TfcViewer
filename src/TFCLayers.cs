    /// <summary>createUniformLayer（与游戏完全一致的层链：uniform + N×(zoom+smooth)）</summary>
    public static Area.Factory CreateUniformLayer(Seed seed, int zoomLevels)
    {
        Area.Factory layer = UniformLayer.Apply(seed.Next());
        for (int i = 0; i < zoomLevels; i++)
        {
            layer = ZoomLayer.ApplyNormal(seed.Next(), layer);
            layer = SmoothLayer.Apply(seed.Next(), layer);
        }
        return layer;
    }
